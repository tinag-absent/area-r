export function getAccessibleDocs(level: number): NovelDocument[] {
  return NOVEL_DOCUMENTS.filter(d => d.clearance <= level);
}

export function getDoc(id: string, level: number): NovelDocument | null {
  const doc = NOVEL_DOCUMENTS.find(d => d.id === id);
  if (!doc || doc.clearance > level) return null;
  return doc;
}

